package main

import (
	"os"
	"strings"
	"text/template"
)

type (
	TypeInfo struct {
		Name      string
		TypeName  string
		ShowName  string
		Delegated bool
	}
)

var header string = `// Generated by gen_types. Don't modify manually!

package core
`

var importFmt string = `
import coretypes "github.com/rcarmo/go-joker/core/types"
`

var ensureObjectIsTemplate string = `
func EnsureObjectIs{{.Name}}(obj coretypes.Object, pattern string) {{.TypeName}} {
{{- if .Delegated }}
	return coretypes.EnsureObjectIs{{.Name}}(obj, pattern)
{{- else }}
	if c, yes := obj.({{.TypeName}}); yes {
		return c
	}
	panic(FailObject(obj, "{{.ShowName}}", pattern))
{{- end }}
}
`

var ensureArgIsTemplate string = `
func EnsureArgIs{{.Name}}(args []coretypes.Object, index int) {{.TypeName}} {
{{- if .Delegated }}
	return coretypes.EnsureArgIs{{.Name}}(args, index)
{{- else }}
	obj := args[index]
	if c, yes := obj.({{.TypeName}}); yes {
		return c
	}
	panic(FailArg(obj, "{{.ShowName}}", index))
{{- end }}
}
`

var infoTemplate string = `
func (x {{.TypeName}}) WithInfo(info *coretypes.ObjectInfo) coretypes.Object {
	x.Info = info
	return x
}
`

func checkError(err error) {
	if err != nil {
		panic(err)
	}
}

func closeFile(f *os.File) {
	checkError(f.Close())
}

func generateAssertions(types []string) {
	filename := "types_assert_gen.go"
	f, err := os.Create(filename)
	checkError(err)
	defer closeFile(f)

	var ensureObjectIs = template.Must(template.New("assert").Parse(ensureObjectIsTemplate))
	var ensureArgIs = template.Must(template.New("ensure").Parse(ensureArgIsTemplate))
	_, err = f.WriteString(header)
	checkError(err)
	_, err = f.WriteString(importFmt)
	checkError(err)
	for _, t := range types {
		typeInfo := TypeInfo{
			Name:     t,
			TypeName: t,
			ShowName: t,
		}
		if t[0] == '*' {
			typeInfo.Name = t[1:]
			typeInfo.ShowName = typeInfo.Name
		}
		if strings.ContainsRune(typeInfo.Name, '.') {
			typeInfo.Name = strings.ReplaceAll(typeInfo.Name, ".", "_")
		}
		if strings.HasPrefix(typeInfo.Name, "coretypes_") || strings.HasPrefix(typeInfo.Name, "io_") {
			continue
		}
		checkError(ensureObjectIs.Execute(f, typeInfo))
		checkError(ensureArgIs.Execute(f, typeInfo))
	}
}

func generateInfo(types []string) {
	filename := "types_info_gen.go"
	f, err := os.Create(filename)
	checkError(err)
	defer closeFile(f)

	var info = template.Must(template.New("info").Parse(infoTemplate))

	_, err = f.WriteString(header)
	checkError(err)
	_, err = f.WriteString(`import coretypes "github.com/rcarmo/go-joker/core/types"
`)
	checkError(err)
	for _, t := range types {
		typeInfo := TypeInfo{
			Name:     t,
			TypeName: t,
		}
		if t[0] == '*' {
			typeInfo.Name = t[1:]
		}
		checkError(info.Execute(f, typeInfo))
	}
}

func main() {
	if len(os.Args) < 2 {
		panic("usage: gen_types <assert|info> [types...]")
	}
	cmd := os.Args[1]
	switch cmd {
	case "assert":
		generateAssertions(os.Args[2:])
	case "info":
		generateInfo(os.Args[2:])
	default:
		panic("unknown command: " + cmd)
	}
}
